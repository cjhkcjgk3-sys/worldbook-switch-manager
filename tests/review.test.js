// Regression tests for the external review of PR #1 (each reproduced on a real 1.19.0 first).
import test from 'node:test';
import assert from 'node:assert/strict';
import { entryKey } from '../core.js';
import { readStart, readDelta } from '../timeline.js';
import { FakeST } from './sim.js';

const DRAGON = 1, CASTLE = 3;
const injected = r => (r.active ?? []).map(e => e.uid);
async function round(st, text, opts) { await st.user(text); return st.generate('normal', opts); }
const DRAGON_INJ = d => Boolean(d?.inj?.some(x => x.join() === 'book,1'));

test('review#1: every swipe generated by one multi-choice request (n=2) records the injection', async () => {
    for (const type of ['normal', 'swipe']) {
        const st = new FakeST();
        await st.user('dragon');
        if (type === 'swipe') { await st.generate('normal', { scanText: 'x' }); }
        await st.generate(type, { n: 2, stream: true });
        const m = st.chat.at(-1);
        const fresh = type === 'swipe' ? m.swipe_info.slice(1) : m.swipe_info;
        assert.ok(fresh.every(i => DRAGON_INJ(i.extra.wsm?.d)), `${type}: ${JSON.stringify(m.swipe_info)}`);
        if (type === 'swipe') assert.equal(DRAGON_INJ(m.swipe_info[0].extra.wsm?.d), false, 'older swipe keeps its own outcome');
        await st.swipeTo(m.swipes.length - 1);
        assert.equal(st.status(DRAGON).cooldown, 2);
        await st.reload();
        assert.equal(st.status(DRAGON).cooldown, 2);
    }
});
test('review#2: a failed request does not consume a cooldown round, retried or followed by a new message', async () => {
    const st = new FakeST({ cooldown: 1 });
    await round(st, 'dragon 1');
    await st.user('dragon fail');
    await st.generate('normal', { fail: true });
    assert.deepEqual(injected(await round(st, 'dragon 3')), [2], 'still cooled: the failed floor merged into this round');
    assert.equal(readStart(st.chat.at(-2)).round, 2);
    assert.deepEqual(injected(await round(st, 'dragon 4')), [1, 2]);
    const retry = new FakeST({ cooldown: 1 });
    await round(retry, 'dragon 1');
    await retry.user('dragon fail');
    await retry.generate('normal', { fail: true });
    assert.deepEqual(injected(await retry.generate('normal')), [2]);
    assert.deepEqual(injected(await round(retry, 'dragon 3')), [1, 2]);
});
test('review#2: two user messages in a row before a reply are one round', async () => {
    const st = new FakeST();
    await round(st, 'dragon');
    await st.user('first'); await st.user('second');
    await st.generate('normal');
    assert.equal(st.status(DRAGON).cooldown, 1);
});
test('review#3: a draft made after a reply does not apply in a branch taken at that round\'s user floor', async () => {
    const st = new FakeST();
    await round(st, 'x 1');
    st.manager.manualFreeze([entryKey('book', CASTLE)], 2);
    await st.reload();
    assert.equal(st.status(CASTLE).manual, 2, 'same position after reload keeps the draft');
    const main = await st.branch(1);
    assert.equal(st.status(CASTLE).manual, 0);
    assert.deepEqual(injected(await round(st, 'castle in branch')), [2, CASTLE]);
    await st.open(main);
    assert.equal(st.status(CASTLE).manual, 2);
    assert.deepEqual(injected(await round(st, 'castle main')), [2]);
});
test('review#3: a draft survives the user message being added before the reply', async () => {
    const st = new FakeST();
    await round(st, 'x 1');
    st.manager.manualFreeze([entryKey('book', CASTLE)], 1);
    await st.user('castle');
    assert.equal(st.status(CASTLE).manual, 1);
    assert.deepEqual(injected(await st.generate('normal')), [2]);
});
test('review#4: visible text before a tool call is not committed if the tool follow-up fails', async () => {
    for (const stream of [true, false]) {
        const st = new FakeST();
        await st.user('dragon');
        await st.generate('normal', { tool: true, toolText: 'I will check.', followFail: true, stream });
        assert.equal(readDelta(st.chat.find(m => m.mes === 'I will check.')), null, `stream=${stream}`);
        assert.equal(st.status(DRAGON).cooldown, 0);
        const ok = new FakeST();
        await ok.user('dragon');
        await ok.generate('normal', { tool: true, toolText: 'I will check.', stream });
        assert.ok(DRAGON_INJ(readDelta(ok.chat.at(-1))), 'successful chain records on the final reply');
        assert.equal(ok.status(DRAGON).cooldown, 2);
    }
});
test('review#5: a dry-run scan before the user message is added does not bind the real request', async () => {
    const st = new FakeST();
    await st.generate('normal', { send: 'dragon 1', preview: true });
    assert.equal(st.status(DRAGON).cooldown, 2);
    const r = [];
    for (let i = 2; i <= 4; i++) r.push(injected(await st.generate('normal', { send: `dragon ${i}`, preview: true })).includes(DRAGON));
    assert.deepEqual(r, [false, false, true]);
});
test('review#6: with aiTurns, a tool message between two AI replies does not break round counting', async () => {
    const st = new FakeST({ aiTurns: true });
    await round(st, 'dragon');
    await st.generate('normal', { tool: true, scanText: 'x' });
    await round(st, 'x');
    assert.equal(readStart(st.chat.at(-2)).round, 3);
    await st.reload();
    assert.deepEqual(injected(await round(st, 'dragon')), [DRAGON, 2]);
});
test('review#7: clearing reports a failed save and can be retried', async () => {
    const st = new FakeST();
    await round(st, 'dragon');
    st.saveFails = true;
    const first = await st.manager.clearChatData();
    assert.equal(first.saved, false);
    assert.match(st.manager.notice, /保存/);
    assert.doesNotMatch(st.manager.notice, /^已清除/);
    st.saveFails = false;
    const second = await st.manager.clearChatData();
    assert.equal(second.saved, true);
    assert.equal(JSON.stringify(st.files.get(st.chatId)).includes('"wsm"'), false);
});
